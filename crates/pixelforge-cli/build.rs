//! Embed `.cursor/skills` into the CLI at compile time.
//!
//! The catalog is generated from the same markdown the repo already ships, so
//! a packaged binary can list and read skills without the git tree.

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let skills_root = manifest
        .join("..")
        .join("..")
        .join(".cursor")
        .join("skills");
    let skills_root = skills_root.canonicalize().unwrap_or_else(|err| {
        panic!(
            "cannot read skill tree at {}: {err}\n\
             pixelforge-cli embeds `.cursor/skills` from the repository root",
            manifest.join("../../.cursor/skills").display()
        )
    });

    println!("cargo:rerun-if-changed={}", skills_root.display());

    let mut skills = Vec::new();
    let mut dirs: Vec<PathBuf> = fs::read_dir(&skills_root)
        .unwrap_or_else(|err| panic!("read {}: {err}", skills_root.display()))
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.is_dir())
        .collect();
    dirs.sort();

    for dir in dirs {
        let name = dir
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("")
            .to_string();
        if name.is_empty() || name.starts_with('.') {
            continue;
        }
        println!("cargo:rerun-if-changed={}", dir.display());
        let skill_md = dir.join("SKILL.md");
        if !skill_md.is_file() {
            panic!(
                "skill `{name}` is missing SKILL.md at {}",
                skill_md.display()
            );
        }
        let description = parse_description(
            &fs::read_to_string(&skill_md)
                .unwrap_or_else(|err| panic!("read {}: {err}", skill_md.display())),
        )
        .unwrap_or_else(|err| panic!("skill `{name}` SKILL.md: {err}"));

        let mut files = vec![("SKILL.md".to_string(), skill_md)];
        let references = dir.join("references");
        if references.is_dir() {
            println!("cargo:rerun-if-changed={}", references.display());
            collect_markdown(&references, "references", &mut files);
        }
        files.sort_by(|a, b| a.0.cmp(&b.0));
        skills.push((name, description, files));
    }

    if skills.is_empty() {
        panic!("no skills found under {}", skills_root.display());
    }

    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("bundled_skills.rs");
    let mut buf = String::new();
    buf.push_str("// Generated by crates/pixelforge-cli/build.rs. Do not edit.\n");
    buf.push_str("pub struct BundledFile {\n");
    buf.push_str("    pub path: &'static str,\n");
    buf.push_str("    pub content: &'static str,\n");
    buf.push_str("}\n\n");
    buf.push_str("pub struct BundledSkill {\n");
    buf.push_str("    pub name: &'static str,\n");
    buf.push_str("    pub description: &'static str,\n");
    buf.push_str("    pub files: &'static [BundledFile],\n");
    buf.push_str("}\n\n");
    buf.push_str("pub static SKILLS: &[BundledSkill] = &[\n");
    for (name, description, files) in &skills {
        buf.push_str("    BundledSkill {\n");
        buf.push_str(&format!("        name: {},\n", rust_str(name)));
        buf.push_str(&format!(
            "        description: {},\n",
            rust_str(description)
        ));
        buf.push_str("        files: &[\n");
        for (rel, abs) in files {
            let include = format!(
                "include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{}\"))",
                path_from_manifest(&manifest, abs)
            );
            buf.push_str("            BundledFile {\n");
            buf.push_str(&format!("                path: {},\n", rust_str(rel)));
            buf.push_str(&format!("                content: {include},\n"));
            buf.push_str("            },\n");
        }
        buf.push_str("        ],\n");
        buf.push_str("    },\n");
    }
    buf.push_str("];\n");

    let mut file = fs::File::create(&out).unwrap();
    file.write_all(buf.as_bytes()).unwrap();
}

fn collect_markdown(dir: &Path, prefix: &str, files: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|err| panic!("read {}: {err}", dir.display()))
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .collect();
    entries.sort();
    for path in entries {
        let name = match path.file_name().and_then(|n| n.to_str()) {
            Some(name) if !name.starts_with('.') => name,
            _ => continue,
        };
        let rel = format!("{prefix}/{name}");
        if path.is_dir() {
            println!("cargo:rerun-if-changed={}", path.display());
            collect_markdown(&path, &rel, files);
        } else if path.is_file() && name.ends_with(".md") && name != "REPORT.md" {
            println!("cargo:rerun-if-changed={}", path.display());
            files.push((rel, path));
        }
    }
}

fn path_from_manifest(manifest: &Path, file: &Path) -> String {
    let manifest = fs::canonicalize(manifest).unwrap();
    let file = fs::canonicalize(file).unwrap();
    let mut prefix = manifest;
    let mut ups = PathBuf::new();
    loop {
        if let Ok(rel) = file.strip_prefix(&prefix) {
            let mut out = ups;
            out.push(rel);
            return out.to_str().unwrap().replace('\\', "/");
        }
        if !prefix.pop() {
            panic!(
                "{} is not reachable from the crate directory",
                file.display()
            );
        }
        ups.push("..");
    }
}

fn rust_str(text: &str) -> String {
    format!("\"{}\"", text.escape_default())
}

fn parse_description(markdown: &str) -> Result<String, String> {
    let rest = markdown
        .strip_prefix("---")
        .ok_or_else(|| "missing YAML frontmatter".to_string())?;
    let rest = rest.strip_prefix('\n').unwrap_or(rest);
    let (front, _) = rest
        .split_once("\n---")
        .ok_or_else(|| "unterminated YAML frontmatter".to_string())?;
    let mut lines = front.lines().peekable();
    while let Some(line) = lines.next() {
        if let Some(value) = line.strip_prefix("description:") {
            let value = value.trim();
            if value == ">" || value == ">-" || value == "|" || value == "|-" {
                let folded = value.starts_with('>');
                let mut parts: Vec<String> = Vec::new();
                while let Some(next) = lines.peek() {
                    if next.starts_with(' ') || next.starts_with('\t') || next.is_empty() {
                        parts.push(lines.next().unwrap().trim().to_string());
                    } else {
                        break;
                    }
                }
                while parts.last().is_some_and(|part| part.is_empty()) {
                    parts.pop();
                }
                if parts.is_empty() {
                    return Err("empty description".into());
                }
                let joined = if folded {
                    parts.join(" ")
                } else {
                    parts.join("\n")
                };
                return Ok(collapse_ws(&joined));
            }
            let trimmed = value.trim_matches(|c| c == '"' || c == '\'').trim();
            if trimmed.is_empty() {
                return Err("empty description".into());
            }
            return Ok(collapse_ws(trimmed));
        }
    }
    Err("frontmatter has no description".into())
}

fn collapse_ws(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}
